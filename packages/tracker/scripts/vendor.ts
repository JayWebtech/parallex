/**
 * Vendors an immutable, version-pinned tracker build.
 *
 *   node scripts/vendor.ts --version 1.0.0 --script /p/1.0.0/px.js --collect /p/e
 *   node scripts/vendor.ts --verify        # CI: re-derive every version, compare bytes
 *
 * Source: `public/script.js` from the pinned Umami image (by digest), i.e. the
 * file Umami's own CI built. The only change is the collect path, rewritten
 * the same way Umami's scripts/update-tracker.js does at container start, plus
 * a license banner. The output is committed, its SHA-384 recorded in
 * tracker-versions.json, and served by the portal with SRI. Upgrading the
 * tracker means vendoring a new version; existing versions never change.
 *
 * Requires Docker (to read the file out of the image without running it).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { parseArgs } from 'node:util';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const configPath = join(root, 'tracker.config.json');
const manifestPath = join(root, 'tracker-versions.json');
const generatedPath = join(root, 'src', 'generated.ts');

interface Upstream {
  project: string;
  version: string;
  image: string;
  file: string;
  defaultCollectPath: string;
  license: string;
}
interface VersionEntry {
  version: string;
  scriptPath: string;
  collectPath: string;
  file: string;
  sha384: string;
  upstream: Omit<Upstream, 'defaultCollectPath' | 'license'> & { sha256: string };
}
interface Manifest {
  current: string;
  versions: VersionEntry[];
}

const { upstream } = JSON.parse(readFileSync(configPath, 'utf8')) as { upstream: Upstream };

function extractUpstream(): Buffer {
  const dir = mkdtempSync(join(tmpdir(), 'tracker-'));
  const container = execFileSync('docker', ['create', upstream.image], { encoding: 'utf8' }).trim();
  try {
    execFileSync('docker', ['cp', `${container}:${upstream.file}`, join(dir, 'script.js')]);
    return readFileSync(join(dir, 'script.js'));
  } finally {
    execFileSync('docker', ['rm', container]);
    rmSync(dir, { recursive: true, force: true });
  }
}

function derive(source: Buffer, version: string, collectPath: string): string {
  const text = source.toString('utf8');
  const occurrences = text.split(upstream.defaultCollectPath).length - 1;
  if (occurrences !== 1) {
    throw new Error(
      `expected exactly one "${upstream.defaultCollectPath}" in upstream, found ${occurrences}`,
    );
  }
  const banner =
    `/*! Parallax tracker ${version}. Derived from ${upstream.project} v${upstream.version} ` +
    `(${upstream.license}). Collect path rewritten to ${collectPath}. */\n`;
  return banner + text.replace(upstream.defaultCollectPath, collectPath);
}

const sha = (algo: string, data: string | Buffer, enc: 'hex' | 'base64') =>
  createHash(algo).update(data).digest(enc);

function writeGenerated(manifest: Manifest): void {
  const sources = Object.fromEntries(
    manifest.versions.map((v) => [v.version, readFileSync(join(root, v.file), 'utf8')]),
  );
  writeFileSync(
    generatedPath,
    `// Generated by scripts/vendor.ts. Do not edit; test/manifest.test.ts checks it.\n` +
      `import type { TrackerManifest } from './types.js';\n\n` +
      `export const TRACKER_MANIFEST: TrackerManifest = ${JSON.stringify(manifest, null, 2)};\n\n` +
      `export const TRACKER_SOURCES: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`,
  );
}

const { values } = parseArgs({
  options: {
    version: { type: 'string' },
    script: { type: 'string' },
    collect: { type: 'string' },
    verify: { type: 'boolean', default: false },
  },
});

const manifest: Manifest = existsSync(manifestPath)
  ? (JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest)
  : { current: '', versions: [] };

if (values.verify) {
  let failed = false;
  const cache = new Map<string, Buffer>();
  for (const entry of manifest.versions) {
    if (entry.upstream.image !== upstream.image) {
      console.log(`skip ${entry.version}: built from ${entry.upstream.image}`);
      continue;
    }
    const source = cache.get(entry.upstream.image) ?? extractUpstream();
    cache.set(entry.upstream.image, source);
    const ok =
      sha('sha256', source, 'hex') === entry.upstream.sha256 &&
      derive(source, entry.version, entry.collectPath) ===
        readFileSync(join(root, entry.file), 'utf8');
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${entry.version}`);
    failed ||= !ok;
  }
  process.exit(failed ? 1 : 0);
}

const { version, script, collect } = values;
if (!version || !script || !collect) {
  console.error('usage: vendor.ts --version X.Y.Z --script /path/name.js --collect /path');
  process.exit(1);
}
if (manifest.versions.some((v) => v.version === version)) {
  console.error(`version ${version} already exists; tracker versions are immutable`);
  process.exit(1);
}

const source = extractUpstream();
const output = derive(source, version, collect);
const file = join('versions', version, script.split('/').at(-1)!);
mkdirSync(join(root, dirname(file)), { recursive: true });
writeFileSync(join(root, file), output);

manifest.versions.push({
  version,
  scriptPath: script,
  collectPath: collect,
  file,
  sha384: `sha384-${sha('sha384', output, 'base64')}`,
  upstream: {
    project: upstream.project,
    version: upstream.version,
    image: upstream.image,
    file: upstream.file,
    sha256: sha('sha256', source, 'hex'),
  },
});
manifest.current = version;
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
writeGenerated(manifest);
console.log(`vendored tracker ${version} → ${file}`);
